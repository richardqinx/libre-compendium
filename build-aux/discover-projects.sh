set -eu
srcdir=$1
output=$2
mkdir -p "$(dirname "$output")"
projects=$(find "$srcdir/math" "$srcdir/physics" -mindepth 2 -maxdepth 2 -type f -name main.tex -printf '%h\n' | sed "s#^$srcdir/##" | sort)
{
  echo '# Generated by discover-projects.sh; do not edit.'
  printf 'DOC_PROJECTS :='
  for project in $projects; do printf ' %s' "$project"; done
  printf '\n'
} > "$output"
